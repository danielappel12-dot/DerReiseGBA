#!/usr/bin/env python3
"""gen_audio.py - compiles the original NIGHTFALL music patterns into data/audio_data.c

The GBA's PSG has two square channels, a 32-sample wave channel and a noise channel.
Music is a step sequencer: every track is 64 sixteenth-note steps long per channel.

Pattern notation (one string per bar of 16 steps):
    NOTE[:len]   e.g. E2:2   note E in octave 2 lasting 2 steps
    -[:len]      rest
Drum bars are written as 16 characters:  K kick, S snare, h closed hat, o open hat,
t tom, . nothing.

Output: note frequency register tables, the wave-channel waveform, tempo table and
all tracks.  Run from the repo root:  python3 tools/gen_audio.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

NOTE_NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}
LOWEST_OCT = 1          # table index 1 == C1
NOTES = 12 * 7          # C1 .. B7


def midi_hz(n):
    return 440.0 * 2 ** ((n - 69) / 12.0)


def note_index(name):
    """'E2' -> 1-based table index (C1 = 1); 0 is reserved for 'rest'"""
    if len(name) >= 3 and name[1] == '#':
        n, o = name[:2], int(name[2:])
    else:
        n, o = name[0], int(name[1:])
    return (o - LOWEST_OCT) * 12 + NOTE_NAMES[n] + 1


def parse_bar(bar, steps=16):
    out = []
    bar = bar.replace(' :', ':')
    for tok in bar.split():
        length = 1
        if ':' in tok:
            tok, l = tok.split(':')
            length = int(l)
        if tok == '-':
            out += [0] * length
        else:
            out += [note_index(tok)] + [255] * (length - 1)
    assert len(out) == steps, (bar, len(out))
    return out


def parse_drums(bar):
    m = {'.': 0, 'K': 1, 'S': 2, 'h': 3, 'o': 4, 't': 5}
    assert len(bar) == 16, bar
    return [m[c] for c in bar]


TRACKS = {}


def track(name, bpm, lead, bass, drums, loop=True):
    TRACKS[name] = dict(bpm=bpm, lead=sum((parse_bar(b) for b in lead), []),
                        bass=sum((parse_bar(b) for b in bass), []),
                        drums=sum((parse_drums(b) for b in drums), []), loop=loop)
    for k in ('lead', 'bass', 'drums'):
        assert len(TRACKS[name][k]) == 64, (name, k, len(TRACKS[name][k]))


