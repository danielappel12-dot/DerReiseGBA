def build():
    lines = ['/* GENERATED by tools/gen_audio.py - original NIGHTFALL music data. Do not edit. */',
             '#include "gba.h"', '#include "audio_data.h"', '']
    # note tables: square channel and wave channel register values (11 bit)
    sq = [0]
    wv = [0]
    for i in range(NOTES):
        hz = midi_hz(24 + i)          # C1 = MIDI 24
        xs = int(round(2048 - 131072.0 / hz))
        xw = int(round(2048 - 65536.0 / hz))
        sq.append(max(0, min(2047, xs)) if xs > 0 else 0)
        wv.append(max(0, min(2047, xw)))
    lines.append('const u16 note_square[NOTE_COUNT + 1] = {' + ','.join(str(v) for v in sq) + '};')
    lines.append('const u16 note_wave[NOTE_COUNT + 1] = {' + ','.join(str(v) for v in wv) + '};')
    # wave channel waveform: a soft sawtooth / triangle mix (32 x 4 bit)
    wave = []
    for i in range(32):
        t = i / 32.0
        tri = 2 * t if t < 0.5 else 2 - 2 * t
        wave.append(max(0, min(15, int(round((0.55 * tri + 0.45 * t) * 15)))))
    words = []
    for i in range(0, 32, 8):
        b = []
        for j in range(4):                     # each byte holds two samples, high nibble first
            b.append((wave[i + j * 2] << 4) | wave[i + j * 2 + 1])
        words.append(b[0] | (b[1] << 8) | (b[2] << 16) | (b[3] << 24))
    lines.append('const u32 wave_table[4] = {' + ','.join('0x%08X' % w for w in words) + '};')
    names = list(TRACKS.keys())
    lines.append('const u16 track_step_x256[%d] = {%s};' % (
        len(names), ','.join(str(int(round(900.0 * 256 / t['bpm']))) for t in TRACKS.values())))
    lines.append('const u8 track_loop[%d] = {%s};' % (len(names), ','.join('1' if t['loop'] else '0' for t in TRACKS.values())))
    for kind in ('lead', 'bass', 'drums'):
        lines.append('const u8 track_%s[%d][64] = {' % (kind, len(names)))
        for t in TRACKS.values():
            lines.append('    {' + ','.join(str(v) for v in t[kind]) + '},')
        lines.append('};')
    open(os.path.join(ROOT, 'data', 'audio_data.c'), 'w').write('\n'.join(lines) + '\n')
    with open(os.path.join(ROOT, 'data', 'audio_data.h'), 'w') as f:
        f.write('/* GENERATED by tools/gen_audio.py */\n#ifndef AUDIO_DATA_H\n#define AUDIO_DATA_H\n#include "gba.h"\n')
        f.write('#define NOTE_COUNT %d\n#define TRACK_COUNT %d\n' % (NOTES, len(names)))
        for i, n in enumerate(names):
            f.write('#define TRACK_%s %d\n' % (n, i))
        f.write('extern const u16 note_square[NOTE_COUNT + 1];\nextern const u16 note_wave[NOTE_COUNT + 1];\n')
        f.write('extern const u32 wave_table[4];\nextern const u16 track_step_x256[TRACK_COUNT];\nextern const u8 track_loop[TRACK_COUNT];\n')
        f.write('extern const u8 track_lead[TRACK_COUNT][64];\nextern const u8 track_bass[TRACK_COUNT][64];\nextern const u8 track_drums[TRACK_COUNT][64];\n#endif\n')
    print('gen_audio: %d tracks, %d notes' % (len(names), NOTES))


if __name__ == '__main__':
    build()
